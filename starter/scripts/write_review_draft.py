def csv_write(name, rows):
    with (AUDIT/name).open('w',encoding='utf-8-sig',newline='') as handle:
        writer=csv.DictWriter(handle,fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)


def main():
    coherence=[]
    for sample in json.loads((OUT/'coherence_samples.json').read_text(encoding='utf-8')):
        strategy=sample['strategy']
        score,reason=COHERENCE['B' if strategy=='C' else strategy][int(sample['sample_id'][1:])-1]
        coherence.append({'strategy':strategy,'sample_id':sample['sample_id'],
                          'document_id':sample['document_id'],'page':sample['page'],
                          'char_offset':sample['char_offset'],'chunk_id':sample['chunk']['chunk_id'],
                          'score':score,'reason':reason,'reviewer':'Codex AI',
                          'status':'ai_draft_pending_human'})
    grounding=[]
    traces=[json.loads(l) for l in (OUT/'traces_test.jsonl').read_text(encoding='utf-8').splitlines()]
    for trace in traces:
        score,reason=GROUNDING[trace['strategy']][int(trace['question_id'][1:])-16]
        grounding.append({'strategy':trace['strategy'],'question_id':trace['question_id'],
                          'score':score,'reason':reason,'reviewer':'Codex AI','status':'ai_draft_pending_human'})
    # Source/page/chapter checked against normalized physical pages and segment
    # text. This is an automatic consistency check plus AI review, not human audit.
    metadata=[]
    from starter.src.ingestion import load_corpus
    segments,_=load_corpus(ROOT/'data/manifest.json',ROOT/'results/run')
    pages={(p['document_id'],p['page']):p for p in
           map(json.loads,(ROOT/'data/processed/pages.jsonl').read_text(encoding='utf-8').splitlines())}
    for trace in traces:
        for rank,hit in enumerate(trace['hits'],1):
            m=hit['metadata']
            source=pages[(m['document_id'],m['page'])]
            assert source['source']==m['source']
            assert source['text'][m['char_start']:m['char_end']]==hit['text']
            matching=[p for p in segments if p.document_id==m['document_id'] and p.page==m['page']
                      and p.metadata['page_offset'] <= m['char_start'] and
                      p.metadata['page_offset']+len(p.text) >= m['char_end']]
            assert matching and any(p.metadata['section']==m['section'] for p in matching)
            metadata.append({'strategy':trace['strategy'],'question_id':trace['question_id'],'rank':rank,
                'chunk_id':hit['chunk_id'],'source':m['source'],'page':m['page'],'section':m['section'],
                'complete_and_correct':True,
                'reason':f"Nguồn phần 2 trang {m['page']}" if m['document_id'].endswith('part2') else f"Nguồn phần 1 trang {m['page']}"})
            metadata[-1]['reason']+=f"; Chương {m['section']}; offsets khớp nguyên văn. Đây là kiểm tra tự động + AI, chờ người học đối chiếu PDF."
            metadata[-1].update(reviewer='Codex AI + consistency check',status='ai_draft_pending_human')
    for name,rows,label in [('coherence',coherence,'score'),('grounding',grounding,'score'),
                            ('metadata',metadata,'complete_and_correct')]:
        csv_write(f'ai_{name}.csv',rows)
        target=AUDIT/f'manual_{name}.csv'
        if not target.exists():
            csv_write(f'manual_{name}.csv',[dict(row)|{label:'','reason':'','reviewer':'','status':'pending_human'} for row in rows])
    summary=[]
    for strategy in 'ABC':
        scores=[r['score'] for r in coherence if r['strategy']==strategy]
        gs=[r['score'] for r in grounding if r['strategy']==strategy]
        filtered=[t for t in traces if t['strategy']==strategy and t['requested_filter']]
        compliant=sum(all(all(h['metadata'].get(k)==v for k,v in t['requested_filter'].items())
                          for h in t['hits']) and len(t['hits'])==3 for t in filtered)
        summary.append({'strategy':strategy,'coherence_ai_mean':sum(scores)/len(scores),'coherence_n':len(scores),
                        'metadata_auto_ai_correct':sum(r['complete_and_correct'] for r in metadata if r['strategy']==strategy),
                        'metadata_n':15,'test_filter_compliant':compliant,'test_filter_n':len(filtered),
                        'grounding_ai_distribution':{str(i):gs.count(i) for i in range(3)},
                        'grounding_ai_mean':sum(gs)/len(gs), 'manual_status':'pending_human'})
    write_json(AUDIT/'draft_summary.json',summary)
    print(json.dumps(summary,ensure_ascii=False,indent=2))


if __name__=='__main__':
    main()
